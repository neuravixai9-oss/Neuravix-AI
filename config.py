# ── Database ──────────────────────────────────────────────────────────────────
# Проект поддерживает ДВА бэкенда БД (см. database/db_backend.py):
#   - PostgreSQL — если задана переменная окружения DATABASE_URL (например,
#     Railway Managed Postgres добавляет её автоматически при подключении
#     плагина Postgres к проекту).
#   - SQLite — если DATABASE_URL не задана (для локальной разработки, либо
#     если Postgres к проекту не подключён). DB_PATH ниже — это путь именно
#     к SQLite-файлу и используется ТОЛЬКО в этом случае.
def _resolve_db_path() -> str:
    explicit = os.getenv("DB_PATH")
    if explicit:
        return explicit

    volume_path = os.getenv("RAILWAY_VOLUME_MOUNT_PATH")
    if volume_path:
        return str(pathlib.Path(volume_path) / "neuravix.db")

    return str(BASE_DIR / "neuravix.db")


